// Generates an interpolated realistic route array between start and end coordinates
export function generateRoutePoints(
  start: { lat: number; lng: number },
  end: { lat: number; lng: number },
  steps = 30
): [number, number][] {
  const points: [number, number][] = [];
  const midLat = (start.lat + end.lat) / 2 + (Math.random() - 0.5) * 0.002;
  const midLng = (start.lng + end.lng) / 2 + (Math.random() - 0.5) * 0.002;

  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    const lat = (1 - t) * (1 - t) * start.lat + 2 * (1 - t) * t * midLat + t * t * end.lat;
    const lng = (1 - t) * (1 - t) * start.lng + 2 * (1 - t) * t * midLng + t * t * end.lng;
    points.push([lat, lng]);
  }
  return points;
}

